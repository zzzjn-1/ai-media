# ---- 向后兼容：llm.py 仍按 list 取前三个词做文案模板 ----
DOMAIN_KW: dict[str, list[str]] = {
    d: [kw for kw, _ in kws] for d, kws in DOMAIN_KEYWORDS.items()
}

# 标题命中权重放大倍数：标题是判定主依据，摘要只作补强
TITLE_MULTIPLIER = 2

# 低于该分不判领域（避免"AI"这类弱词把社会新闻误判成科技）
MIN_DOMAIN_SCORE = 3


def score_domains(text: str, title: str = "") -> dict[str, int]:
    """对一段文本按领域打分。title 与 text 可相同（只传 text 时按标题权重计）。"""
    haystack_title = (title or text or "").upper()
    haystack_body = (text or "").upper() if title else ""
    scores: dict[str, int] = {}
    for domain, kws in DOMAIN_KEYWORDS.items():
        total = 0
        for kw, weight in kws:
            k = kw.upper()
            if haystack_title and k in haystack_title:
                total += weight * TITLE_MULTIPLIER
            elif haystack_body and k in haystack_body:
                total += weight
        if total:
            scores[domain] = total
    return scores


def detect_domain(title: str, summary: str = "") -> tuple[str, list[str]]:
    """判定主领域。

    返回 (main_domain, matched_keywords)：
      - 命中且分数 >= MIN_DOMAIN_SCORE → 该领域
      - 否则 → "综合"（调用方据此决定「综合」不进入 5 个官方领域筛选）
    """
    scores = score_domains(summary or "", title=title)
    if not scores:
        return "综合", []
    best_domain = max(scores, key=lambda d: scores[d])
    if scores[best_domain] < MIN_DOMAIN_SCORE:
        return "综合", []
    matched = [
        kw for kw, _ in DOMAIN_KEYWORDS[best_domain]
        if kw.upper() in (title or "").upper() or kw.upper() in (summary or "").upper()
    ]
    return best_domain, matched
